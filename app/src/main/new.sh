# 1. สร้างและสลับไปยัง branch ใหม่ชื่อ Labmobile10-06-69
git checkout -b Labmobile10-06-69

# 2. เพิ่มไฟล์ทั้งหมดที่พึ่งแก้ไข/สร้างใหม่เข้าสู่ระบบ Git Track
git add .

# 3. บันทึกประวัติการเปลี่ยนแปลง (Commit)
git commit -m "Complete My Student Profile Card app with full state control"

# 4. อัปโหลดโค้ดขึ้น GitHub ไปยัง branch ใหม่ที่สร้างไว้
git push -u origin Labmobile10-06-69